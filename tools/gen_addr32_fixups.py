#!/usr/bin/env python3
"""Turn address words in u32 data tables into startup fixups (64-bit PC port).

GameCube data tables (ape_data.inc, data_init_gen.c, ...) store pointers as
u32 words, e.g. `(u32)"EARL"` or `(uint32_t)(uintptr_t)&sym`.  On x86_64 such
an initializer is not an address constant, so GCC rejects it.  The x64 port
keeps every game address below 4 GiB (docs/x64.md), so a 32-bit word can
still hold the address; it just has to be stored at startup.

This tool rewrites each address element `CAST EXPR` of every top-level
`T NAME[N] = { ... };` array into `PC_A32(EXPR)` (which is `(u32)(EXPR)` on
GC / 32-bit and `0` on 64-bit) and writes a fixup table
`{ &NAME[index], (const void *)(EXPR) }` that pc_apply_addr32_fixups()
stores at startup.

Address-macro elements: if IN defines one-argument macros of the form
`#define P0(i) PC_A32(&ARR[i])` (or `(u32)&ARR[i]`), each array element
`P0(expr)` is left as it is (the macro already expands to PC_A32) and gets
the fixup `{ &NAME[index], &ARR[expr] }` (baseball_stage_data.inc).

usage: gen_addr32_fixups.py IN OUT_SOURCE OUT_FIXUPS SYMBOL
       (OUT_SOURCE '-' = do not write a rewritten source)
"""
import re
import sys

CASTS = [r'\(uint32_t\)\(uintptr_t\)', r'\(u32\)']
ELEM_RE = re.compile(r'^\s*(?:%s)\s*(.+?)\s*$' % '|'.join(CASTS), re.S)
MACRO_DEF_RE = re.compile(
    r'^\s*#\s*define\s+(\w+)\((\w+)\)\s+(?:PC_A32\(\s*&\s*(\w+)\s*\[\s*\2\s*\]\s*\)'
    r'|\(u32\)\s*&\s*(\w+)\s*\[\s*\2\s*\])\s*$', re.M)
ARRAY_RE = re.compile(r'^([A-Za-z_][\w ]*?\b)(\w+)((?:\[[^\]]*\])+)([^=;\n]*)=\s*\{', re.M)


def split_top(body):
    out, depth, cur = [], 0, ''
    for ch in body:
        if ch in '({[':
            depth += 1
        elif ch in ')}]':
            depth -= 1
        if ch == ',' and depth == 0:
            out.append(cur)
            cur = ''
        else:
            cur += ch
    out.append(cur)
    return out


def main():
    src_path, out_src, out_fix, sym = sys.argv[1:5]
    s = open(src_path).read()
    macros = {}
    for mm in MACRO_DEF_RE.finditer(s):
        macros[mm.group(1)] = mm.group(3) or mm.group(4)
    macro_re = None
    if macros:
        macro_re = re.compile(r'^\s*(%s)\((.+)\)\s*$' % '|'.join(map(re.escape, macros)), re.S)
    fixups = []
    pos = 0
    res = []
    for m in ARRAY_RE.finditer(s):
        if m.start() < pos:
            continue
        name = m.group(2)
        dims = re.findall(r'\[([^\]]*)\]', m.group(3))
        # find matching close brace
        i = m.end()
        depth = 1
        while depth:
            if s[i] == '{':
                depth += 1
            elif s[i] == '}':
                depth -= 1
            i += 1
        body = s[m.end():i - 1]
        if not any(re.search(c, body) for c in CASTS) and not (
                macro_re and re.search(r'\b(%s)\(' % '|'.join(macros), body)):
            continue
        # flatten nested braces for multi-dim arrays: index = running count
        flat_parts = []
        idx = [0]
        def walk(text):
            parts = split_top(text)
            out = []
            for p in parts:
                st = p.strip()
                if st.startswith('{') and st.endswith('}'):
                    inner = st[1:-1]
                    lead = p[:len(p) - len(p.lstrip())]
                    out.append(lead + '{' + walk(inner) + '}')
                    continue
                if st == '':
                    out.append(p)
                    continue
                mm = macro_re.match(p) if macro_re else None
                em = ELEM_RE.match(p)
                if mm:
                    fixups.append((name, idx[0], '&%s[%s]' % (macros[mm.group(1)], mm.group(2).strip())))
                    out.append(p)
                elif em:
                    expr = em.group(1)
                    lead = p[:len(p) - len(p.lstrip())]
                    trail = p[len(p.rstrip()):]
                    fixups.append((name, idx[0], expr))
                    out.append('%sPC_A32(%s)%s' % (lead, expr, trail))
                else:
                    out.append(p)
                idx[0] += 1
            return ','.join(out)
        # multi-dim arrays with nested braces must be fully bracketed per row
        # of the innermost dimension for the flat index to be right
        newbody = walk(body)
        res.append(s[pos:m.end()])
        res.append(newbody)
        pos = i - 1
    res.append(s[pos:])
    if out_src != '-':
        open(out_src, 'w').write(''.join(res))
    with open(out_fix, 'w') as f:
        f.write('/* GENERATED by pc_port/tools/gen_addr32_fixups.py from %s.\n'
                ' * 64-bit PC port only: address words of u32 tables, stored at\n'
                ' * startup (see pc_addr32.h).  %d fixups. */\n'
                % (src_path.split('/')[-1], len(fixups)))
        f.write('static const struct PcAddr32Fixup %s[] = {\n' % sym)
        for name, ix, expr in fixups:
            f.write('    { (u32 *)%s + %d, (const void *)(%s) },\n' % (name, ix, expr))
        f.write('};\n')
    print('%d fixups' % len(fixups))


if __name__ == '__main__':
    main()
