#!/usr/bin/env python3
"""Generate src/game/shim/stubs_gen.c from a failed link's build log.

Classifies each `undefined reference` symbol against the decomp's symbol
maps (config/GM2E8P/**/symbols.txt): objects become zeroed data blobs of
their real (32-byte rounded) size; functions become log-once stubs.
Float-returning functions (per decomp headers) return 0.0 via st(0).

Usage: gen_stubs.py <build_log> <out_c>
"""
import glob
import os
import re
import sys

DECOMP = os.environ.get("SMB2_DECOMP_DIR",
                        os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "..", "decomp"))

# Symbols the maps don't cover, with hand-chosen classification.
# The ape face "buffers" are NlObj*/TPL* pointer slots (nl2ngc.c load_nlobj).
OVERRIDES = {
    "g_ape_face_gma_buf": ("object", 4),
    "g_ape_face_tpl_buf": ("object", 4),
    # Race CPU table (race2.c fn_10_13B94: 0x80 x 16-byte entries). The map
    # splits it at D338C/D3390/D3394 (debug-menu aliases of entry 0), so its
    # own size is listed as 4; a 32-byte stub overflowed into D336C-D3374
    # (camera mode 12 projection offsets) and broke frustum culling in race.
    "lbl_1_bss_D3388": ("object", 0x800),
    # Dogfight profiling timers (dogfight_7.c: u32[0x12], cleared every frame).
    # A 32-byte stub overflowed into D4CDC/D4CD8 (the COM-player mask), so on
    # 32-bit the CPUs lost their 0x800 flag (no COM score list, wrong AI).
    "lbl_1_bss_D4CE4": ("object", 0x48),
    # Boat profiling counters (u32[0xC] and u32[0x13], updated every frame)
    # and the debug CPU path table (BoatCpuPoint[0x80]): sizes from the GC
    # layout (D4334..D4364..D43B0, D43B4..), 32-byte stubs overflowed.
    "lbl_1_bss_D4334": ("object", 0x30),
    "lbl_1_bss_D4364": ("object", 0x4C),
    "lbl_1_bss_D43B4": ("object", 0x600),
    # Target (pilot2_stage.c) profiling timers: u32[0x15], cleared/added
    # every frame; the map lists D49C0.. as separate 4-byte symbols.
    "lbl_1_bss_D49BC": ("object", 0x54),
    # window.c debug light editor copy: struct Light (0x4C).
    "lbl_1_bss_6F30": ("object", 0x4C),
}

# Function stubs whose callers expect a pointer or floating-point return
# value: a K&R `int f()` stub returns in eax/st(0) per its own type, which
# leaves the upper half of rax (x64) or the x87 stack (32-bit, double
# callers) undefined.  Emit a real prototype instead.  The float table below
# only sees decomp headers; these are declared in .c files.
TYPED_FUNCS = {
    "find_stage_or_bg_model": "void *%s()",   # struct GMAModel *(char *name)
    "fn_8000F954": "char *%s()",              # OSGetFontTexture
    "fn_8005AF8C": "void *%s()",              # ADX work alloc
    "fn_80065C94": "void *%s()",              # (tpl, idx) -> texture
    "fn_8006F330": "void *%s()",              # fopen-like (path, mode)
    "fn_8007682C": "double %s()",             # (double) -> double
}

# Symbols the link log lists but that a decomp TU now defines as a
# tentative (common, -fcommon) definition.  A stub would win over the
# common symbol with its GC-map size, which is too small on x64 (the TU's
# real type holds pointers): BoatPlayer[8], GMAModel *[0x4D], SelNgcMenuWork.
SKIP = {"g_currently_visible_menu_screen", "lbl_14_bss_208", "lbl_14_bss_B4"}

def main():
    log_path, out_path = sys.argv[1], sys.argv[2]
    with open(log_path, encoding="utf-8", errors="replace") as f:
        log = f.read()
    undef = sorted(set(re.findall(
        r"undefined reference to `([A-Za-z_$][A-Za-z0-9_$]*)'", log)))
    if not undef:
        print("no undefined references found in", log_path)

    # symbol maps: name -> (type, size)
    info = {}
    maps = glob.glob(DECOMP + "/config/GM2E8P/symbols.txt") + \
           glob.glob(DECOMP + "/config/GM2E8P/*/symbols.txt")
    pat = re.compile(
        r"(\w+)\s*=\s*[^;]+;\s*//\s*type:(\w+)(?:\s+size:0x([0-9A-Fa-f]+))?")
    for mf in maps:
        with open(mf, encoding="utf-8", errors="replace") as f:
            for line in f:
                m = pat.match(line.strip())
                if m and m.group(1) not in info:
                    info[m.group(1)] = (m.group(2), int(m.group(3) or "0", 16))

    # float-returning function names from decomp headers
    hdr_text = []
    for hf in glob.glob(DECOMP + "/include/**/*.h", recursive=True):
        with open(hf, encoding="utf-8", errors="replace") as f:
            hdr_text.append(f.read())
    floatfns = set(re.findall(r"\b(?:f32|f64|float|double)\s+(\w+)\s*\(",
                              "\n".join(hdr_text)))

    out = ["/* AUTO-GENERATED by tools/gen_stubs.py from the link log.",
           " * Do not edit; regenerate instead. */",
           "void shim_log_once(const char *sym);",
           "/* Data blobs are sized from the GC symbol maps; the decomp may declare",
           " * them as pointer-bearing types, which are up to 2x larger on x64. */",
           "#define PC_STUB_SCALE (sizeof(void *) / 4)", ""]
    ndata = nfn = nunk = 0
    for s in undef:
        if s in SKIP:
            continue
        t, size = OVERRIDES.get(s) or info.get(s, (None, 0))
        looks_data = re.match(r"lbl_(\d+_)?(bss|data|80)", s)
        if t == "object" or (t is None and looks_data):
            if t is None:
                size = 4096  # unknown data: be generous
                tag = " /* not in symbol maps */"
            else:
                tag = ""
            size = max(size, 32)
            size = (size + 31) & ~31
            out.append("unsigned char %s[%d * PC_STUB_SCALE] __attribute__((aligned(32)));%s"
                       % (s, size, tag))
            ndata += 1
        else:
            tag = "" if t else " /* not in symbol maps */"
            if not t:
                nunk += 1
            nfn += 1
            if s in TYPED_FUNCS:
                ret = TYPED_FUNCS[s].split("%s")[0].strip()
                zero = "0.0" if ret == "double" else "0"
                out.append('%s { shim_log_once("%s"); return %s; }%s'
                           % (TYPED_FUNCS[s] % s, s, zero, tag))
            elif s in floatfns:
                out.append('double %s() { shim_log_once("%s"); return 0.0; }%s'
                           % (s, s, tag))
            else:
                out.append('int %s() { shim_log_once("%s"); return 0; }%s'
                           % (s, s, tag))
    with open(out_path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("stubs_gen.c: %d function stubs (%d unmapped), %d data objects"
          % (nfn, nunk, ndata))

if __name__ == "__main__":
    main()
